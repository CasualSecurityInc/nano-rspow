#!/usr/bin/env python3
"""Pin build-produced 12-round predicated kernels to their SIMD widths."""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
out = ['/* Generated by make-snb-engine.py; detects accidental blob/width mismatches. */',
       '#ifndef SNB_ENGINE_H', '#define SNB_ENGINE_H']
for lanes in (8, 16):
    stem = here / f'm3-12-l{lanes}-pred'
    data = stem.with_suffix('.bin').read_bytes()
    metadata = json.loads(stem.with_suffix('.json').read_text())
    if not (metadata['rounds'] == 12 and metadata['nonces_per_thread'] == lanes
            and metadata['predicated_carry'] and metadata['bytes'] == len(data)):
        raise SystemExit(f'invalid production kernel metadata: {stem}')
    checksum = 0xcbf29ce484222325
    for byte in data:
        checksum = ((checksum ^ byte) * 0x100000001b3) & (2**64 - 1)
    out += [f'#define ENGINE{lanes}_BYTES {len(data)}u',
            f'#define ENGINE{lanes}_CHECKSUM UINT64_C(0x{checksum:016x})']
out += ['#endif', '']
(here / 'snb-engine.h').write_text('\n'.join(out))
