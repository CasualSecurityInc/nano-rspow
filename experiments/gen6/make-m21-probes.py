#!/usr/bin/env python3
"""Emit small Gen6 assembly probes; expected arithmetic is checked independently."""
from pathlib import Path

HERE = Path(__file__).resolve().parent
A = [0, 0xffffffff, 0xffffffffffffffff, 0x12345678ffffffff,
     0x8000000000000000, 0x0123456789abcdef, 0xffffffffffffffff, 0xfffffffe00000001]
B = [0, 1, 1, 0x0000000100000001,
     0x8000000000000000, 0xfedcba9876543210, 0xffffffffffffffff, 0x00000001ffffffff]


def mov(dst, src, width=8):
    return f'mov ({width}) {dst}<1>:UD {src} {{align1}};'


def imm(reg, value, width=8):
    return mov(reg, f'0x{value:08x}:UD', width)


def vec(reg):
    return f'r{reg}.0<8,8,1>:UD'


def header(offset=0):
    return [imm('r4.0', 0),
            'mov (1) r4.20<1>:UB r0.20<0,1,0>:UB {align1};',
            imm('r4.8', offset, 1)]


def write(regs, control=4):
    lines = [mov('m0.0', vec(4))]
    lines += [mov(f'm{i+1}.0', vec(reg)) for i, reg in enumerate(regs)]
    lines += [f'send (16) 0 r16 null data_port(5, 8, {control}, 0, 1, 1) mlen {len(regs)+1} rlen 1 {{align1}};',
              # Consume the write-commit response before reusing message registers/EOT.
              mov('r17.0', vec(16))]
    return lines


def end():
    return [mov('m0.0', vec(0)),
            'send (16) 0 acc0<1>UW null thread_spawner(0, 0, 1) mlen 1 rlen 0 {align1 EOT};']


def save(name, lines, description):
    (HERE / f'm21{name}.asm').write_text(f'/* {description}\n * Generated by make-m21-probes.py. */\n' + '\n'.join(lines) + '\n')


for size in (16, 128, 256):
    lines = header()
    blocks = 2 if size == 256 else 1
    for block in range(blocks):
        regs = range(20, 21 if size == 16 else 24)
        for reg in regs:
            for lane in range(8):
                lines.append(imm(f'r{reg}.{4*lane}', 0x61000000 + block*32 + (reg-20)*8 + lane, 1))
        lines += [imm('r4.8', block*8, 1)] + write(regs, 0 if size == 16 else 4)
    save(f'pattern{size}', lines + end(), f'Exact {size}-byte constant-pattern write; offsets 0 and optionally 8 OWords.')

# First 128 bytes are incoming R0..R3. Second 128 bytes are known constants,
# avoiding expectations about uninitialized R4..R7 contents.
lines = [imm(f'r{10+i}.0', 0xaaaa0000+i) for i in range(4)]
lines += header() + write(range(4))
lines += [imm('r4.8', 8, 1)] + write(range(10, 14)) + end()
save('dump2', lines, 'Dump R0..R3, followed by four marker GRFs at byte 128; M0 address is at byte 8.')

lines = header()
lines += [mov('r20.0', vec(3)),
          'mov (1) r20.12<1>:UD r0.20<0,1,0>:UD {align1};',
          'shl (1) r4.8<1>:UD r3.0<0,1,0>:UD 1:UD {align1};']
lines += write([20], 2) + end()  # Control 2 = two OWords, NOT control 1.
save('slots', lines, 'One 32-byte record per packet, inline R3.0 selects slot; DW3 records the dispatch header.')

lines = [imm(f'r20.{4*i}', 0x101+i, 1) for i in range(8)]
lines += header() + [mov('m0.0', vec(4)),
                    mov('m1.0', 'r20.0<4,4,1>:UD')]
lines += [mov(f'm{i+2}.0', vec(i+1)) for i in range(3)]
lines += ['send (16) 0 r16 null data_port(5, 8, 4, 0, 1, 1) mlen 5 rlen 1 {align1};',
          mov('r17.0', vec(16))] + end()
save('lane', lines, 'Eight distinct lane values gathered with region <4,4,1>, then CURBE and inline registers.')

lines = []
for i, (a, b) in enumerate(zip(A, B)):
    for reg, value in ((20, a & 0xffffffff), (21, a >> 32), (22, b & 0xffffffff), (23, b >> 32)):
        lines.append(imm(f'r{reg}.{4*i}', value, 1))
lines += [
    'add (8) r24.0<1>:UD r20.0<8,8,1>:UD r22.0<8,8,1>:UD {align1};',
    'cmp.l.f0.0 (8) r26.0<1>:UD r24.0<8,8,1>:UD r20.0<8,8,1>:UD {align1};',
    'and (8) r26.0<1>:UD r26.0<8,8,1>:UD 1:UD {align1};',
    'add (8) r25.0<1>:UD r21.0<8,8,1>:UD r23.0<8,8,1>:UD {align1};',
    'add (8) r25.0<1>:UD r25.0<8,8,1>:UD r26.0<8,8,1>:UD {align1};',
    imm('r28.0', 0x55555555),
    '(f0.0) mov (8) r28.0<1>:UD 0xaaaaaaaa:UD {align1};',
]
# Rotate the resulting 64-bit sum using 32-bit shifts and ORs.
for shift, lo, hi in ((24, 30, 31), (63, 32, 33)):
    if shift < 32:
        ops = [(lo, 'shr', 24, shift), (34, 'shl', 25, 32-shift),
               (hi, 'shr', 25, shift), (35, 'shl', 24, 32-shift)]
    else:  # ROR63 = ROL1.
        ops = [(lo, 'shl', 24, 1), (34, 'shr', 25, 31),
               (hi, 'shl', 25, 1), (35, 'shr', 24, 31)]
    for dest, op, src, amount in ops:
        lines.append(f'{op} (8) r{dest}.0<1>:UD {vec(src)} {amount}:UD {{align1}};')
    lines += [f'or (8) r{lo}.0<1>:UD {vec(lo)} {vec(34)} {{align1}};',
              f'or (8) r{hi}.0<1>:UD {vec(hi)} {vec(35)} {{align1}};']
lines += header() + write([24, 25, 30, 31])
lines += [imm('r4.8', 8, 1)] + write([32, 33, 26, 28]) + end()
save('arith', lines, 'Eight u64 addition cases with carry, ROR24/ROR63, and per-lane flag predication.')
